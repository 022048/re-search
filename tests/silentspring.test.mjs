import * as S from '../js/sim/silentspring.js';
let ok = 0, bad = 0;
const t = (n, c) => { if (c) { ok++; console.log('ok', n); } else { bad++; console.log('FAIL', n); } };
t('DDD가 기름에 99% 이상', S.fracOil(6) > 0.99);
t('설탕은 물에 남는다', S.fracOil(-2) < 1e-4);
t('DDD 사슬: 물 0.02 → 새 1000 ppm 이상', S.chain(S.COMPOUNDS.ddd, 0.02)[4].ppm > 1000);
t('약제 C 사슬은 거의 오르지 않는다', S.chain(S.COMPOUNDS.fast, 0.02)[4].ppm < 0.1);
for (const dose of [0.25, 0.5, 1, 2]) t(`DDD ${dose}배는 새 한계를 넘는다`, S.judge({ id: 'ddd', dose, n: 1 }).maxGrebe > S.GREBE_LIMIT);
t('시작 계획(DDD 1배 1회)은 실패', !S.judge({ id: 'ddd', dose: 1, n: 1 }).checks.every((c) => c.ok));
t('추천 계획(C 1.5배 4회)은 통과', S.judge({ id: 'fast', dose: 1.5, n: 4 }).checks.every((c) => c.ok));
t('약제 B 1배 2회는 통과', S.judge({ id: 'mid', dose: 1, n: 2 }).checks.every((c) => c.ok));
t('반감기 계산', Math.abs(S.remain(10, 10) - 0.5) < 1e-9);
console.log(`${ok} passed, ${bad} failed`); process.exit(bad ? 1 : 0);
